import re

import pymupdf as fitz


class ExtractionAgent:
    """
    Extracts basic financial metrics from annual-report text.

    Each result stores source-page evidence. It does not create values
    that are not present in the report.
    """

    METRICS = [
        ("Revenue", ["total net sales", "net sales", "total revenue", "revenue"]),
        (
            "Cost of Revenue",
            ["cost of sales", "cost of revenue", "cost of products sold"],
        ),
        ("Gross Profit", ["gross profit"]),
        (
            "Operating Income",
            ["operating income", "income from operations"],
        ),
        ("Net Income", ["net income", "net earnings", "net profit"]),
        (
            "Basic EPS",
            ["basic earnings per share", "basic net income per share"],
        ),
        (
            "Diluted EPS",
            ["diluted earnings per share", "diluted net income per share"],
        ),
        (
            "Cash and Cash Equivalents",
            ["cash and cash equivalents"],
        ),
        (
            "Accounts Receivable",
            ["accounts receivable", "trade receivables"],
        ),
        ("Inventory", ["inventories", "inventory"]),
        ("Total Assets", ["total assets"]),
        ("Total Liabilities", ["total liabilities"]),
        (
            "Shareholders Equity",
            ["shareholders' equity", "stockholders' equity"],
        ),
        ("Long Term Debt", ["long-term debt", "long term debt"]),
        (
            "Operating Cash Flow",
            [
                "cash generated by operating activities",
                "net cash provided by operating activities",
            ],
        ),
        (
            "Capital Expenditure",
            [
                "capital expenditures",
                "payments for property, plant and equipment",
            ],
        ),
        ("Free Cash Flow", ["free cash flow"]),
    ]

    AMOUNT_PATTERN = re.compile(
        r"[$₹€£]?\s?\d{1,3}(?:,\d{3})+(?:\.\d+)?"
        r"|[$₹€£]?\s?\d+(?:\.\d+)?\s?"
        r"(?:billion|million|thousand|bn|mn)",
        re.IGNORECASE,
    )

    def run(
        self,
        file_path: str,
        fiscal_year: str | None,
    ) -> list[dict]:
        pdf = fitz.open(file_path)
        pages = []

        try:
            for page_number, page in enumerate(pdf, start=1):
                text = page.get_text("text").strip()

                if text:
                    pages.append(
                        {
                            "page": page_number,
                            "text": text,
                        }
                    )
        finally:
            pdf.close()

        results = []

        for metric_name, aliases in self.METRICS:
            metric = self.find_metric(
                metric_name=metric_name,
                aliases=aliases,
                pages=pages,
                fiscal_year=fiscal_year,
            )

            if metric:
                results.append(metric)

        return results

    def find_metric(
        self,
        metric_name: str,
        aliases: list[str],
        pages: list[dict],
        fiscal_year: str | None,
    ) -> dict | None:
        for page in pages:
            lines = page["text"].splitlines()

            for index, line in enumerate(lines):
                evidence = " ".join(line.split())
                lower_evidence = evidence.lower()

                if not any(alias in lower_evidence for alias in aliases):
                    continue

                amount = self.find_amount(evidence)

                if not amount:
                    nearby_text = " ".join(lines[index:index + 3])
                    amount = self.find_amount(nearby_text)

                if not amount:
                    continue

                unit = self.find_unit(page["text"])

                if unit and unit.lower() not in amount.lower():
                    amount = f"{amount} {unit}"

                return {
                    "metric_name": metric_name,
                    "metric_value": amount,
                    "period": (
                        f"FY {fiscal_year}"
                        if fiscal_year
                        else "Annual report period"
                    ),
                    "source_page": page["page"],
                    "evidence": evidence[:1000],
                    "confidence": 0.90,
                }

        return None

    def find_amount(self, text: str) -> str | None:
        for value in self.AMOUNT_PATTERN.findall(text):
            value = value.strip()
            number_text = re.sub(r"[^\d.]", "", value)

            try:
                number = float(number_text)

                if 1900 <= number <= 2100 and "," not in value:
                    continue

                return value
            except ValueError:
                continue

        return None

    def find_unit(self, page_text: str) -> str | None:
        text = page_text.lower()

        if "(in millions)" in text or "dollars in millions" in text:
            return "(in millions)"

        if "(in billions)" in text or "dollars in billions" in text:
            return "(in billions)"

        if "(in thousands)" in text or "dollars in thousands" in text:
            return "(in thousands)"

        return None